'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const Astronomy=require('astronomy-engine');
const {Solar}=require('lunar-javascript');
const C=require('../assets/triple-cycle-core.js');
const B=require('../assets/bazi-core.js');
const Astro=require('../ea/combined2/vendor/astro-core.cjs');
const month='2026-10',bounds=C.bounds(month);
assert.equal(C.VERSION,'1.0.0');
assert.equal(bounds.start,Date.UTC(2026,9,1)-7*3600000);
assert.equal(bounds.end,Date.UTC(2026,10,1)-7*3600000);
assert.throws(()=>C.bounds('2026-13'),/Pilih bulan/);
assert.throws(()=>C.bounds('2041-01'),/2020/);
assert.equal(C.PHASES.length,8);
assert.equal(C.PHASES[0].angle,0);
assert.equal(C.PHASES[4].angle,180);
const moon=C.lunarEvents(Astronomy,month);
assert.ok(moon.events.length>=8&&moon.events.length<=10,'Eight phase angles should recur around once in 29.5 days');
assert.ok(moon.events.some(x=>x.angle===0),'New moon is present in the selected month');
assert.ok(moon.events.some(x=>x.angle===180),'Full moon is present in the selected month');
assert.ok(moon.events.every(x=>x.ms>=bounds.start&&x.ms<bounds.end));
assert.ok(moon.events.every((x,i)=>i===0||x.ms>moon.events[i-1].ms));
const periods=C.baziPeriods(B,Solar,month);
assert.equal(periods[0].start,bounds.start);
assert.equal(periods.at(-1).end,bounds.end);
assert.ok(periods.length>=2,'October must cross a solar term and change its month pillar');
assert.ok(periods.every(x=>x.end>x.start&&B.SHIO.includes(x.month.animal)&&B.ELEMENTS.includes(x.month.element)));
assert.ok(periods.every((x,i)=>i===0||periods[i-1].end===x.start));
assert.ok(periods[0].month.text!==periods.at(-1).month.text);
let count=0;
const days=C.astrologyDays(Astro,Astronomy,month,()=>count++);
assert.equal(days.length,31);assert.equal(count,31);
assert.equal(days[0].date,'2026-10-01');
assert.equal(days.at(-1).date,'2026-10-31');
assert.ok(days.every(x=>['BUY','SELL','TRANSISI','NETRAL'].includes(x.state)));
assert.ok(days.every(x=>x.snapshots.length===3&&x.snapshots.every(s=>Number.isFinite(s.score)&&s.speeds&&Number.isFinite(s.speeds.Mercury))));
const merged=C.enrich(days,periods,moon,Astronomy);
assert.ok(merged.every(x=>Number.isFinite(x.moonAgeHours)&&x.moonAgeHours>=0&&x.moonAgeHours<31*24));
assert.ok(merged.every(x=>x.elongation>=0&&x.elongation<360));
assert.ok(merged.every(x=>x.bazi.month.animal&&x.bazi.year.element));
assert.ok(merged.every(x=>x.hijri===null||typeof x.hijri==='string'));
const summary=C.summarize(merged);
assert.equal(summary.total,31);
assert.equal(Object.values(summary.counts).reduce((n,x)=>n+x,0),31);
assert.equal(summary.groups.reduce((n,x)=>n+x.days,0),31);
assert.ok(['BUY','SELL','CAMPURAN'].includes(summary.direction));
assert.ok(summary.groups.every(g=>g.start<g.end&&g.peak>=g.start&&g.peak<g.end));
assert.ok(C.highlights(merged[0]).length<=4);
assert.throws(()=>C.astrologyDays(Astro,Astronomy,month,()=>{},()=>true),/dibatalkan/);
const html=fs.readFileSync('index.html','utf8'),navigation=fs.readFileSync('assets/bazi-ui.js','utf8');
const ui=fs.readFileSync('assets/triple-cycle-ui.js','utf8');
assert.ok(html.includes('assets/triple-cycle-core.js?v=1.1.0'));
assert.ok(html.includes('assets/triple-cycle-ui.js?v=1.2.0'));
assert.ok(html.indexOf('assets/triple-cycle-core.js')<html.indexOf('assets/triple-cycle-ui.js'));
assert.ok(navigation.includes('data-bz-target="tcPanel"'));
assert.ok(navigation.includes("tabTriple"),'Direct Triple Cycle tab must be visible');
assert.ok(navigation.includes("location.hash==='#triple-cycle'"),'Hash must open the Triple Cycle directly');
assert.ok(ui.includes("jumps.insertAdjacentElement('afterend',panel)"),'Triple Cycle must appear immediately after BaZi shortcuts on mobile');
assert.ok(ui.includes("cebonk:triple-open"),'Open tab must start the monthly calculation');
assert.ok(navigation.includes("'f60Panel','tcPanel'"));
assert.ok(ui.includes('Bulan Baru')===false,'Lunar phase names are owned by the core');
assert.ok(ui.includes('Umm al-Qura')&&ui.includes('bukan'));
assert.ok(!/[\u3400-\u9fff]/u.test(ui),'User-facing UI contains no Hanzi');
assert.ok(!html.includes('technical-scanners-ui.js'));
console.log('PASS Triple Cycle: October 2026 real ephemeris, 8 phases, solar-term BaZi boundaries, Hijri reference, daily astrology snapshots, CSV UI, legacy preserved.');
