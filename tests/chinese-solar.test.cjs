'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const Astronomy=require('astronomy-engine');
const {Solar}=require('lunar-javascript');
const T=require('../assets/chinese-solar-core.js');
const Bazi=require('../assets/bazi-core.js');
const Bias=require('../assets/astro-moment-bias.js');
const Research=require('../ea/combined2/vendor/astro-core.cjs');
assert.equal(T.VERSION,'1.0.0');
assert.equal(T.SPEC.length,24);
assert.deepEqual(T.SPEC.filter(e=>e.season).map(e=>e.angle),[315,45,135,225]);
assert.equal(T.SPEC.filter(e=>e.kind==='JIE').length,12);
assert.equal(T.SPEC.filter(e=>e.kind==='QI').length,12);
assert.ok(T.SPEC.every(e=>!(/[\u3400-\u9fff]/u).test(e.name)));
assert.throws(()=>T.yearTerms(null,2026),/Astronomy Engine/);
assert.throws(()=>T.yearTerms(Astronomy,2019),/2020/);
assert.throws(()=>T.yearTerms(Astronomy,2041),/2020/);
assert.equal(T.weekend(Date.UTC(2026,9,10,12)).friday,'2026-10-09');
assert.equal(T.weekend(Date.UTC(2026,9,11,12)).monday,'2026-10-12');
assert.equal(T.weekend(Date.UTC(2026,9,9,12)),null);
const years=[2020,2026,2028,2040];
for(const y of years){
 const t=T.yearTerms(Astronomy,y);
 assert.equal(t.events.length,24);
 assert.equal(t.seasons.length,4);
 assert.equal(t.events.filter(x=>x.kind==='JIE').length,12);
 assert.ok(t.events.every((e,i)=>i===0||e.ms>t.events[i-1].ms));
 assert.ok(t.events.every(e=>e.wib.date.startsWith(String(y))));
 assert.ok(t.events.every(e=>e.wib.month===e.month));
 assert.ok(t.events.every(e=>e.angle>=0&&e.angle<360));
 assert.ok(t.events.every(e=>e.bridge===null||e.bridge.friday<e.wib.date&&e.bridge.monday>e.wib.date));
 assert.equal(Array.from({length:12},(_,i)=>T.filterMonth(t,i+1).length).reduce((a,b)=>a+b,0),24);
 assert.ok(Array.from({length:12},(_,i)=>T.filterMonth(t,i+1).length).every(n=>n===2));
 for(const e of t.events){
  const repeat=Astronomy.SearchSunLongitude(e.angle,new Date(e.ms-60000),0.2);
  assert.ok(repeat&&Math.abs(+repeat.date-e.ms)<2000,'Solar crossing must be reproducible');
 }
}
const oct=T.yearTerms(Astronomy,2026);
assert.equal(T.filterMonth(oct,10)[0].name,'Embun Dingin');
assert.equal(T.filterMonth(oct,10)[0].angle,195);
assert.ok(T.filterMonth(oct,10)[0].wib.date>='2026-10-07'&&T.filterMonth(oct,10)[0].wib.date<='2026-10-09');
const spring=oct.seasons[0];
assert.equal(spring.name,'Awal Musim Semi');
assert.ok(spring.wib.date>='2026-02-03'&&spring.wib.date<='2026-02-05');
assert.equal(oct.seasons[1].name,'Awal Musim Panas');
assert.equal(oct.seasons[2].name,'Awal Musim Gugur');
assert.equal(oct.seasons[3].name,'Awal Musim Dingin');
const before=Bazi.calculate(Solar,'2026-02-03','12:00'),after=Bazi.calculate(Solar,'2026-02-05','12:00');
assert.equal(before.pillars.year.animal,'Ular');
assert.equal(after.pillars.year.animal,'Kuda');
// Research engine is not rewritten: inject it directly into the existing monthly bias adapter.
const items=[...oct.seasons,...T.filterMonth(oct,10)];
const biases=Bias.calculate(Astronomy,items,Research);
assert.equal(Object.keys(biases).length,new Set(items.map(x=>x.ms)).size);
assert.ok(items.every(e=>['BUY','SELL','NEUTRAL'].includes(biases[e.ms].event.state)));
assert.ok(items.every(e=>Number.isFinite(biases[e.ms].event.score)));
const sum=Bias.summary(T.filterMonth(oct,10),biases);
assert.ok(['BUY','SELL','MIXED'].includes(sum.state));
assert.equal(sum.available,2);
assert.equal(sum.count.BUY+sum.count.SELL+sum.count.NEUTRAL,2);
const html=fs.readFileSync('index.html','utf8'),ui=fs.readFileSync('assets/chinese-solar-ui.js','utf8');
assert.ok(html.includes('assets/chinese-solar-core.js?v=1.0.0'));
assert.ok(html.includes('assets/chinese-solar-ui.js?v=1.0.0'));
assert.ok(html.indexOf('chinese-solar-core.js')<html.indexOf('chinese-solar-ui.js'));
assert.ok(html.indexOf('astro-moment-bias.js')<html.indexOf('chinese-solar-ui.js'));
assert.ok(ui.includes("tab.textContent='KALENDER CINA'"));
assert.ok(ui.includes("history.replaceState(null,'','#kalender-cina')"));
assert.ok(ui.includes('B.calculate(await getAstronomy(),all,C)'),'Use ONLY inherited Astrology model via shared adapter');
assert.ok(!/[\u3400-\u9fff]/u.test(ui),'No Hanzi in visible new Chinese calendar');
assert.ok(!ui.includes('submitOrder')&&!ui.includes('OrderSend'));
for(const preserved of ['assets/triple-cycle-ui.js','assets/bazi-ui.js','assets/astro-weekly-ui.js','assets/astro-news-v1.js'])assert.ok(html.includes(preserved));
console.log('PASS Chinese calendar: 24 solar terms, 4 season gateways, 12 BaZi month openings, true ephemeris, WIB, unchanged Astrology V1 research, legacy intact.');
