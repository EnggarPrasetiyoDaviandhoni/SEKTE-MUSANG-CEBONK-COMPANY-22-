'use strict';
const assert=require('node:assert/strict');
const F=require('../assets/astrodox-follow-trend-core.js');
const BASE=Date.UTC(2026,9,14,0,0,0),STEP=5*60000;
const opts={confirmBars:3,graceBars:3,stepMinutes:5,buyThreshold:1.15,sellThreshold:-1.15};
const samples=scores=>scores.map((score,i)=>({ms:BASE+i*STEP,score}));
const x=F.calculate(samples([2,2,2,2,0,-2,-2,-2]),opts);
assert.equal(x.source,'CEBONK_ASTROLOGY_V1_ONLY');
assert.equal(x.model,'ASTRODOX_V1_FOLLOW_TREND_RESEARCH');
assert.equal(x.validated,false);
assert.equal(x.tradeDecision,'WAIT');
assert.deepEqual(x.rows.map(r=>r.state),['WAIT','WAIT','BUY','BUY','WAIT','WAIT','WAIT','SELL']);
assert.equal(x.rows[5].reason,'PERINGATAN_PERUBAHAN_ARAH');
assert.equal(x.rows[7].state,'SELL','reverse requires three *completed* opposite bars');
assert.equal(x.reversals,1);
assert.equal(x.buyMinutes,10);
assert.equal(x.sellMinutes,5);
assert.equal(x.waitMinutes,25);
assert.equal(x.windows.length,2);
assert.equal(x.windows[0].start,BASE+2*STEP,'AWAL occurs only upon confirmation, not backdated');
assert.equal(x.windows[0].end,BASE+4*STEP);
assert.equal(x.windows[1].start,BASE+7*STEP);
assert.equal(x.focus,'BUY');
assert.equal(x.focusWindow.start,BASE+2*STEP);
assert.equal(x.focusWindow.coreScore,2);
assert.equal(x.directionalShare,2/3);
assert.equal(x.rows.at(-1).persistentTrend,'SELL');
const flipFail=F.calculate(samples([2,2,2,-2,-2,2,2,2]),opts);
assert.deepEqual(flipFail.rows.map(r=>r.state),['WAIT','WAIT','BUY','WAIT','WAIT','BUY','BUY','BUY']);
assert.equal(flipFail.reversals,0,'two opposite bars do not produce reversal');
const reset=F.calculate(samples([2,2,2,0,0,0,2,2,2]),opts);
assert.deepEqual(reset.rows.map(r=>r.state),['WAIT','WAIT','BUY','WAIT','WAIT','WAIT','WAIT','WAIT','BUY']);
const alternating=F.calculate(samples([2,-2,2,-2,2,-2,2,-2]),opts);
assert.equal(alternating.focus,'WAIT');
assert.equal(alternating.windows.length,0);
assert.equal(alternating.tradeDecision,'WAIT');
const neutral=F.calculate(samples([0,0,0,0,0]),opts);
assert.equal(neutral.focus,'WAIT');
assert.equal(neutral.directionalShare,null);
const prefix=[2,2,2,0,-2,-2,2,2,2];
const full=F.calculate(samples(prefix),opts);
for(let i=0;i<prefix.length;i++){
 const partial=F.calculate(samples(prefix.slice(0,i+1)),opts);
 assert.deepEqual(partial.rows,full.rows.slice(0,i+1),'no future scores may alter previously confirmed trend state');
}
assert.equal(F.rawDirection(1.15,1.15,-1.15),'BUY');
assert.equal(F.rawDirection(-1.15,1.15,-1.15),'SELL');
assert.equal(F.rawDirection(0,1.15,-1.15),'WAIT');
assert.throws(()=>F.calculate(samples([2,NaN,2]),opts),/Skor/);
assert.throws(()=>F.calculate(samples([2,null,2]),opts),/Skor/);
assert.throws(()=>F.calculate([{ms:BASE,score:2},{ms:BASE+1000,score:2}],opts),/Urutan/);
assert.throws(()=>F.calculate(samples([2,2]),{...opts,buyThreshold:0}),/Ambang/);
assert.throws(()=>F.calculate(samples([2,2]),{...opts,confirmBars:0}),/Konfirmasi/);
assert.throws(()=>F.calculate([],opts),/Data skor/);
assert.equal(F.VERSION,'1.0.0');
console.log('PASS ASTRODOX FOLLOW TREND: causal confirmation, reversal warning, neutral reset, AWAL/INTI/AKHIR, WAIT and strict validation.');
