'use strict';
const assert=require('node:assert/strict');
const P=require('../assets/primbon-dagang.js');
const millis=(date,time)=>Date.parse(date+'T'+time+':00+07:00');
const see=(date,time)=>P.evaluate(millis(date,time));
const mon=see('2026-10-12','10:00');
assert.equal(mon.weton,'Senin Pahing','independently documented pasaran anchor');
assert.equal(mon.sri,false,'Senin Pahing is not in No.159 Sri row');
assert.equal(mon.saatAgungLabel,'Rejeki','No.147 Senin 09–11 WIB');
assert.equal(mon.saatAgung.good,true);
assert.equal(see('2026-10-12','12:00').saatAgungLabel,'Malaekat','No.147 Senin 11–13 WIB');
assert.equal(see('2026-10-12','17:00').saatAgungLabel,'DI LUAR TABEL','No.147 does not label all hours');
assert.equal(see('2026-10-13','17:59').weton,'Selasa Pon');
assert.equal(see('2026-10-13','18:00').weton,'Rabu Wage','after assumed 18:00 sunset uses next Javanese date');
assert.equal(see('2026-10-13','18:00').sri,true,'Rabu Wage No.159 Sri');
assert.equal(see('2026-10-13','18:00').saatAgungLabel,'DI LUAR TABEL','No.147 civil weekday hour out of table');
assert.equal(see('2026-10-14','07:00').saatAgungLabel,'Rejeki','No.147 Rabu 06–08');
assert.equal(see('2026-10-14','07:00').sri,true);
assert.equal(see('2026-10-15','14:00').saatAgungLabel,'Cahya','No.147 Kamis 13–15');
assert.equal(see('2026-10-16','15:00').saatAgungLabel,'Rejeki','No.147 Jumat 14–16');
assert.equal(see('2026-10-18','12:00').weton,'Minggu Pon');
assert.equal(see('2026-10-18','12:00').sri,true);
assert.equal(see('2026-10-22','12:00').weton,'Kamis Pahing');
assert.equal(see('2026-10-22','12:00').sri,true);
assert.equal(see('2026-11-09','10:00').weton,'Senin Kliwon');
assert.equal(see('2026-11-09','10:00').sri,true,'Kliwon not universally unlucky');
assert.equal(see('2026-10-11','12:00').weton,'Minggu Legi');
const weekStart=new Date(millis('2026-10-12','00:00'));
const oneFullCycle=P.evaluate(weekStart.getTime()+35*86400000);
assert.equal(oneFullCycle.weton,'Senin Pahing','35-day cycle exact');
assert.ok(P.SAAT_START_END.every(x=>x.length===8));
assert.ok(P.SAAT_START_END.every(x=>x.every((v,i)=>i===0||v>x[i-1])));
assert.throws(()=>P.evaluate(NaN),/ora valid/);
assert.throws(()=>P.evaluate(millis('2026-10-12','12:00'),{sunsetMinuteWIB:1500}),/ora valid/);
console.log('PASS: No.159 Sri 35-day pasaran, No.147 saat windows, 18:00 date transition, and no invented hours.');
