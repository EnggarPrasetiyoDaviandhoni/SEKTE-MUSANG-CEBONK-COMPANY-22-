'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
let html=fs.readFileSync('index.html','utf8');
const marker='<script id="pdfModeLoader"';assert.ok(html.includes(marker),'Current PDF loader required');
const tags='<script src="assets/snd-auto-core.js?v=1.0.0"></script>\n<script src="assets/snd-auto-ui.js?v=1.0.0"></script>\n';
if(!html.includes('assets/snd-auto-core.js'))html=html.replace(marker,tags+marker);
assert.equal((html.match(/src="assets\/snd-auto-core.js/g)||[]).length,1);
assert.equal((html.match(/src="assets\/snd-auto-ui.js/g)||[]).length,1);
assert.ok(html.indexOf('src="assets/musang-pdf-core.js')<html.indexOf('src="assets/snd-auto-core.js'));
assert.ok(html.indexOf('src="assets/snd-auto-ui.js')<html.indexOf(marker));
fs.writeFileSync('index.html',html);
let ui=fs.readFileSync('assets/musang-pdf-ui.js','utf8');
ui=ui.replace('locations:i===2?zones:[]','locations:i===2?decision.context.aligned:[],locationSource:i===2?"AUTO_ENGINEERING":"NONE"');
